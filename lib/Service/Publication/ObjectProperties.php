namespace OCA\OpenCatalogi\Service\Publication;

/**
 * Reads an object entity, or a plain object, as its property array.
 *
 * @spec openspec/changes/hermiq-ai-tooling/specs/mcp-tool-surface/spec.md#requirement-publish-depublish-and-archive-execute-only-after-a-server-verified-human-approval-req-009
 */
final class ObjectProperties {

	/**
	 * The properties of an object: its serialisation when it has one, else its public fields.
	 *
	 * @param object $object The object, an OpenRegister entity or a plain object.
	 *
	 * @return array<string, mixed> Its properties.
	 *
	 * @spec openspec/changes/hermiq-ai-tooling/specs/mcp-tool-surface/spec.md#requirement-publish-depublish-and-archive-execute-only-after-a-server-verified-human-approval-req-009
	 */
	public static function of(object $object): array {
		if (method_exists($object, 'jsonSerialize') === true) {
			$data = $object->jsonSerialize();
			if (is_array($data) === true) {
				return $data;
			}
		}

		return get_object_vars($object);
	}//end of()
}//end class
